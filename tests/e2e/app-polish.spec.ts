import {test,expect} from '@playwright/test';
import {initializeApp} from 'firebase-admin/app';
import {getFirestore} from 'firebase-admin/firestore';
import {randomUUID} from 'node:crypto';
import {initialProcedureDraft} from '../../shared/procedures';
import {signInGoogle} from './auth-helper';
const db=getFirestore(initializeApp({projectId:'demo-placementstats'},'app-polish-tests'));
test('shared shell stays stable and theme preference survives sections and reload',async({page},info)=>{
 await signInGoogle(page);
 await page.goto('/#companies');await expect(page.getByRole('textbox',{name:'Search companies'})).toBeVisible();
 const before=await page.locator('.app-header').boundingBox(),brand=await page.locator('.app-header .brand').boundingBox();
 const quick=page.getByRole('navigation',{name:'Quick navigation'});
 if(info.project.name==='mobile')await quick.getByRole('link',{name:'Experiences',exact:true}).click();
 else await page.getByRole('navigation',{name:'App',exact:true}).getByRole('link',{name:'Company Procedures',exact:true}).click();
 await expect(page.getByRole('heading',{name:'Company Procedures',exact:true})).toBeVisible();
 expect(await page.locator('.app-header').boundingBox()).toEqual(before);
 expect(await page.locator('.app-header .brand').boundingBox()).toEqual(brand);
 await page.getByRole('button',{name:'Switch to dark mode'}).click();
 await expect(page.locator('html')).toHaveAttribute('data-theme','dark');
 await page.reload();await expect(page.getByRole('button',{name:'Switch to light mode'})).toBeVisible();
 expect(await page.evaluate(()=>getComputedStyle(document.body).backgroundColor)).toBe('rgb(8, 8, 8)');
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 await page.screenshot({path:`artifacts/app-dark-${info.project.name}.png`});
 await page.getByRole('button',{name:'Switch to light mode'}).click();
 await expect(page.locator('html')).toHaveAttribute('data-theme','light');
});
test('reader shows writing without comparison or questions; fetching respects reduced motion',async({page},info)=>{
 const owner=await signInGoogle(page),id=randomUUID();
 await db.doc(`procedurePosts/${id}`).set({...initialProcedureDraft(),id,title:'A clean reading experience',companyKey:'barclays',companyName:'Barclays',body:'## My coding round\nI solved an array problem, explained its complexity and discussed SQL joins.\n\n## Preparation\nPractise explaining projects clearly.',authorUid:owner,authorName:'A contributor',published:true,publishedAt:Date.now(),revision:1,score:0,upvotes:0,downvotes:0});
 await page.route('**/*',async route=>{if(new URL(route.request().url()).port==='8080')await new Promise(resolve=>setTimeout(resolve,1200));await route.continue();});
 await page.goto(`/#procedures/${id}`);
 await expect(page.getByRole('status').filter({hasText:'Loading experience'})).toBeVisible();
 await page.emulateMedia({reducedMotion:'reduce'});
 expect(await page.locator('.fetch-hourglass').first().evaluate(el=>getComputedStyle(el).animationName)).toBe('none');
 await expect(page.getByRole('heading',{name:'A clean reading experience'})).toBeVisible();
 await page.unroute('**/*');
 await expect(page.locator('.reader-view .procedure-markdown')).toContainText('I solved an array problem');
 await expect(page.getByLabel('Ask a question')).toHaveCount(0);
 await expect(page.getByRole('button',{name:'Compare',exact:true})).toHaveCount(0);
 await expect(page.getByRole('navigation',{name:'Experience sections'})).toHaveCount(0);
 await expect(page.getByText('A contributor',{exact:false})).not.toBeVisible();
 await page.locator('.reader-context summary').click();await expect(page.getByText('By A contributor.',{exact:false})).toBeVisible();
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 await page.screenshot({path:`artifacts/reader-clean-${info.project.name}.png`});
});
