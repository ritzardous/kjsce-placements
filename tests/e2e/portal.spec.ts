import { test, expect } from '@playwright/test';
import { signInGoogle } from './auth-helper';
test.beforeEach(() => {
  if (process.env.E2E_FIREBASE !== 'true') throw new Error('Use the isolated Firebase test runner.');
});
test('public landing and protected deep links never read placement documents before sign-in', async ({ page }) => {
  const reads: string[] = [];
  page.on('request', request => { if (request.url().includes(':8080')) reads.push(request.url()); });
  await page.goto('/');
  await expect(page.getByRole('heading', { name: /Your placement prep/ })).toBeVisible();
  await expect(page.getByRole('button', { name: 'Continue with Google' })).toBeEnabled();
  await expect(page.getByRole('textbox')).toHaveCount(0);
  await page.goto('/#2025/company/google');
  await expect(page.getByRole('heading', { name: 'Good to see you.' })).toBeVisible();
  await expect(page.getByText(/take you back to the page/)).toBeVisible();
  expect(reads).toEqual([]);
  await signInGoogle(page, false);
  await expect(page).toHaveURL(/#2025\/company\/google$/);
  await expect(page.getByRole('heading', { name: 'Google', exact: true })).toBeVisible();
  await page.reload();
  await expect(page.getByRole('heading', { name: 'Google', exact: true })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
});
